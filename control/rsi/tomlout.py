"""TOML output for Codex: a whole config file, or the same config as `-c key=value` flags.

Every value is written inline on one line, so a top-level key and its value form a complete `-c` flag.
"""
import re

BARE_KEY = re.compile(r'[A-Za-z0-9_-]+')
ESCAPES = {'"': '\\"', '\\': '\\\\', '\b': '\\b', '\t': '\\t', '\n': '\\n', '\f': '\\f', '\r': '\\r'}


def _string(text: str) -> str:
    out = []
    for char in text:
        if char in ESCAPES:
            out.append(ESCAPES[char])
        elif char < ' ' or char == '\x7f':
            out.append(f'\\u{ord(char):04x}')
        else:
            out.append(char)
    return '"' + ''.join(out) + '"'


def _key(key) -> str:
    if not isinstance(key, str):
        raise TypeError(f'TOML key must be a string, not {type(key).__name__}: {key!r}')
    return key if BARE_KEY.fullmatch(key) else _string(key)


def toml_value(value) -> str:
    """Render str, bool, int, float, list and dict as inline TOML; anything else is a TypeError."""
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, str):
        return _string(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, list):
        return '[' + ', '.join(toml_value(item) for item in value) + ']'
    if isinstance(value, dict):
        return '{' + ', '.join(f'{_key(key)} = {toml_value(item)}' for key, item in value.items()) + '}'
    raise TypeError(f'no TOML form for {type(value).__name__}: {value!r}')


def render_file(config: dict) -> str:
    """A config.toml: a generated-by comment, then one `key = value` line per top-level key, in dict order."""
    lines = ['# generated by rsi']
    lines += [f'{_key(key)} = {toml_value(value)}' for key, value in config.items()]
    return '\n'.join(lines) + '\n'


def render_flags(config: dict) -> list[str]:
    """The same config as Codex `-c key=value` flags, one pair per top-level key, keys sorted."""
    flags = []
    for key in sorted(config):
        flags += ['-c', f'{_key(key)}={toml_value(config[key])}']
    return flags
